import { readdirSync, writeFileSync } from 'node:fs'

// Regenerates app/lib/constants/page-content/index.ts from the files in that
// folder, so a new page's wording is picked up by the editor and the seed
// without anyone remembering to register it. Run: npm run generate:page-content
const dir = new URL('../app/lib/constants/page-content/', import.meta.url)
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .sort()

const name = (file) => file.replace(/\.ts$/, '').replace(/-(\w)/g, (_, c) => c.toUpperCase())

const out = `// Generated by scripts/generate-page-content-index.js. Do not edit by hand.
import type { PageContentDefs } from '@/app/lib/page-content/copy'
${files.map((f) => `import { pageContent as ${name(f)} } from './${f.replace(/\.ts$/, '')}'`).join('\n')}

export const PAGE_CONTENT: PageContentDefs[] = [
${files.map((f) => `  ${name(f)}`).join(',\n')}
]

export const pageContentFor = (slug: string) => PAGE_CONTENT.find((page) => page.slug === slug) ?? null
`

writeFileSync(new URL('index.ts', dir), out)
console.log(`✓ page-content index: ${files.length} pages`)
